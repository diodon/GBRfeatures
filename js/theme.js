const Theme = {
  _current: 'dark',

  init() {
    const saved = localStorage.getItem('gbr-theme') || 'dark';
    this._apply(saved, false);
    document.getElementById('btn-theme').addEventListener('click', () => {
      this._apply(this._current === 'dark' ? 'light' : 'dark', true);
    });
  },

  _apply(theme, save) {
    this._current = theme;
    if (theme === 'light') {
      document.documentElement.setAttribute('data-theme', 'light');
    } else {
      document.documentElement.removeAttribute('data-theme');
    }
    if (save) localStorage.setItem('gbr-theme', theme);
    this._updateButton();
  },

  _updateButton() {
    const btn = document.getElementById('btn-theme');
    if (!btn) return;
    if (this._current === 'dark') {
      btn.title = 'Switch to light theme';
      btn.innerHTML = `<svg xmlns="http://www.w3.org/2000/svg" width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><circle cx="12" cy="12" r="5"/><line x1="12" y1="1" x2="12" y2="3"/><line x1="12" y1="21" x2="12" y2="23"/><line x1="4.22" y1="4.22" x2="5.64" y2="5.64"/><line x1="18.36" y1="18.36" x2="19.78" y2="19.78"/><line x1="1" y1="12" x2="3" y2="12"/><line x1="21" y1="12" x2="23" y2="12"/><line x1="4.22" y1="19.78" x2="5.64" y2="18.36"/><line x1="18.36" y1="5.64" x2="19.78" y2="4.22"/></svg>`;
    } else {
      btn.title = 'Switch to dark theme';
      btn.innerHTML = `<svg xmlns="http://www.w3.org/2000/svg" width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M21 12.79A9 9 0 1 1 11.21 3 7 7 0 0 0 21 12.79z"/></svg>`;
    }
  }
};
